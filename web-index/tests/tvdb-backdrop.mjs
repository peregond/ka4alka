import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const code = ts.transpileModule(fs.readFileSync(new URL('../lib/tvdb-backdrop.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const api = {}; vm.runInNewContext(code, { exports: api, require: () => ({}), Response, URL, AbortSignal, TextDecoder, Uint8Array, JSON });
const show = { section: 'series', title: 'Чернобыль', originalTitle: 'Chernobyl', year: 2019 };
assert.equal(api.matchSeries([{ tvdb_id: '1', name: 'Chernobyl', year: '2019' }], show), 1);
assert.equal(api.matchSeries([{ tvdb_id: '1', name: 'Chernobyl', year: '2019' }, { tvdb_id: '2', name: 'Chernobyl', year: '2019' }], show), null);
assert.equal(api.matchSeries([{ tvdb_id: '1', name: 'Other', year: '2019', translations: { rus: 'Чернобыль' } }], show), 1);
assert.equal(api.matchSeries([{ tvdb_id: '1', name: 'Chernobyl', year: '1990' }], show), null);
for (const bad of ['http://artworks.thetvdb.com/banners/a.jpg', 'https://evil.test/banners/a.jpg', 'https://artworks.thetvdb.com/banners/../a.jpg', 'https://artworks.thetvdb.com/banners/a.png']) assert.equal(api.tvdbImageUrl(bad), null);
const art = (image, type, width, height, language, score = 1) => ({ image, type, width, height, language, score });
const u = n => `https://artworks.thetvdb.com/banners/v4/series/1/backgrounds/${n}.jpg`;
assert.equal(api.selectTvdbBackdrop([art(u('poster'), 2, 1920, 1080, null), art(u('en'), 3, 1920, 1080, 'eng', 9), art(u('ru'), 3, 1920, 1080, 'rus'), art(u('clean'), 3, 1920, 1080, null), art(u('tiny'), 3, 400, 225, null)]), u('clean'));
const calls = [];
const fake = async (url, options) => {
  calls.push(url); assert.equal(options.redirect, 'manual');
  if (url.endsWith('/login')) return Response.json({ data: { token: 'tok' } });
  assert.equal(options.headers.Authorization, 'Bearer tok'); assert(!url.includes('tok'));
  if (url.includes('/search?')) return Response.json({ data: [{ tvdb_id: '7', name: 'Chernobyl', year: '2019' }] });
  return Response.json({ data: { artworks: [art(u('clean'), 3, 1920, 1080, null)] } });
};
const got = await api.fetchTvdbBackdrop(show, 'key', fake);
assert.deepEqual({ ...got }, { url: u('clean'), tvdbId: 7, source: 'TVDB' });
assert(calls.some(c => c.includes('series/7/artworks')));
assert.equal(await api.fetchTvdbBackdrop({ ...show, section: 'movies' }, 'key', fake), null);
await assert.rejects(api.fetchTvdbBackdrop(show, 'key', async () => new Response('x', { status: 401 })), /temporarily unavailable/);
console.log('tvdb ok');
